import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const tsRoot = resolve(import.meta.dir, "..");
const repoRoot = resolve(tsRoot, "..", "..");
const outputPath = resolve(tsRoot, "src/generated/tables.ts");

const tableSource = await readFile(
  resolve(repoRoot, "crates/avatar-tables/src/generated/tables.rs"),
  "utf8",
);
const paletteSource = await readFile(
  resolve(repoRoot, "crates/avatar-genome/src/generated/palette.rs"),
  "utf8",
);

function valuesFor(source: string, name: string): bigint[] {
  const match = source.match(
    new RegExp(`pub const ${name}: \\[[^\\n]+\\] = \\[([\\s\\S]*?)\\];`),
  );
  if (!match) {
    throw new Error(`could not find Rust constant ${name}`);
  }

  return [...match[1].matchAll(/\d+/g)].map(([value]) => BigInt(value));
}

function formatValues(values: readonly bigint[], width = 12): string {
  const lines: string[] = [];
  for (let index = 0; index < values.length; index += width) {
    lines.push(`  ${values.slice(index, index + width).map((value) => `${value}n`).join(", ")},`);
  }
  return lines.join("\n");
}

function formatPalette(values: readonly bigint[]): string {
  const expectedValues = 2048 * 6 * 3;
  if (values.length !== expectedValues) {
    throw new Error(`PALETTE_BASE has ${values.length} channel values, expected ${expectedValues}`);
  }

  const slots: string[] = [];
  for (let slot = 0; slot < 2048; slot += 1) {
    const colors: string[] = [];
    for (let color = 0; color < 6; color += 1) {
      const offset = (slot * 6 + color) * 3;
      colors.push(`[${values.slice(offset, offset + 3).map((value) => `${value}n`).join(", ")}]`);
    }
    slots.push(`  [${colors.join(", ")}],`);
  }
  return slots.join("\n");
}

const tableDefinitions = [
  ["SIN_QUARTER", 4096],
  ["EASE_LINEAR", 256],
  ["EASE_EXPO", 256],
  ["EASE_IN_CIRC", 256],
  ["EASE_IN_QUINT", 256],
  ["EASE_IN_OUT_CIRC", 256],
] as const;

const tables = tableDefinitions.map(([name, length]) => {
  const values = valuesFor(tableSource, name);
  if (values.length !== length) {
    throw new Error(`${name} has ${values.length} values, expected ${length}`);
  }
  return `export const ${name} = [\n${formatValues(values)}\n] as const;`;
});

const palette = valuesFor(paletteSource, "PALETTE_BASE");
const output = `// @generated by scripts/import-tables.ts — do not edit\n//\n// These values are transcribed from the committed Rust tables, never reminted.\n// Runtime math must consume this shared data so every port has the same bytes.\n\n${tables.join("\n\n")}\n\nexport const PALETTE_BASE = [\n${formatPalette(palette)}\n] as const;\n`;

await mkdir(resolve(tsRoot, "src/generated"), { recursive: true });
await writeFile(outputPath, output);
