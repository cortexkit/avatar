//! Mints the committed Voronoi pattern table from the historical TOG source.
//!
//! The TOG renderer ships five pre-baked SVG path strings used as body-pattern
//! masks (`voronoiPatterns.ts`). This crate vendors those strings verbatim as
//! spec data rather than depending on the TS checkout at runtime: the
//! committed bytes, not the local source checkout, are the specification. This
//! program exists only to make that committed data reproducible when the
//! vendored table is intentionally refreshed.

use std::{
    env,
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};

fn main() {
    let source = env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(default_source_path);
    let output = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/generated/voronoi.rs");
    let text = fs::read_to_string(&source)
        .unwrap_or_else(|error| panic!("read {}: {error}", source.display()));
    let patterns =
        extract_patterns(&text).unwrap_or_else(|error| panic!("{}: {error}", source.display()));

    fs::create_dir_all(output.parent().expect("voronoi output has a parent"))
        .unwrap_or_else(|error| panic!("create {}: {error}", output.display()));
    fs::write(&output, mint_source(&patterns))
        .unwrap_or_else(|error| panic!("write {}: {error}", output.display()));
    println!(
        "wrote {} ({} patterns) from {}",
        output.display(),
        patterns.len(),
        source.display()
    );
}

fn default_source_path() -> PathBuf {
    let home = env::var_os("HOME").expect("HOME is required to locate the TOG source");
    Path::new(&home).join(
        "Work/Projects/Ssbd/tog-monorepo/packages/playground/src/components/SsbdSvg/\
         voronoiPatterns.ts",
    )
}

/// Extracts every single-quoted path string from the `voronoiPatterns` array.
///
/// The vendored strings are raw SVG path data; they embed into Rust string
/// literals unescaped, so anything outside the path-data alphabet is rejected
/// here rather than silently carried into the committed table.
fn extract_patterns(source: &str) -> Result<Vec<String>, String> {
    let marker = "export const voronoiPatterns";
    let declaration = source
        .find(marker)
        .ok_or("missing voronoiPatterns declaration")?;
    let tail = &source[declaration..];
    let array_start = tail.find('[').ok_or("missing array open bracket")?;
    let array_end = tail.find("];").ok_or("missing array close bracket")?;
    if array_end <= array_start {
        return Err("array close precedes array open".to_owned());
    }
    let body = &tail[array_start + 1..array_end];

    let mut patterns = Vec::new();
    let mut rest = body;
    while let Some(open) = rest.find('\'') {
        let after_open = &rest[open + 1..];
        let close = after_open.find('\'').ok_or("unterminated pattern string")?;
        let pattern = &after_open[..close];
        validate_path_data(pattern)?;
        patterns.push(pattern.to_owned());
        rest = &after_open[close + 1..];
    }
    if patterns.is_empty() {
        return Err("no pattern strings found".to_owned());
    }
    Ok(patterns)
}

fn validate_path_data(pattern: &str) -> Result<(), String> {
    for character in pattern.chars() {
        let allowed = character.is_ascii_alphanumeric()
            || matches!(character, ' ' | '.' | ',' | '-' | '\n' | '\r' | '\t');
        if !allowed {
            return Err(format!(
                "unexpected character {character:?} in pattern data"
            ));
        }
    }
    Ok(())
}

fn mint_source(patterns: &[String]) -> String {
    let mut source = String::from(
        "// @generated by src/bin/mint_voronoi.rs — do not edit\n\n\
         // Voronoi body-pattern path data vendored from the historical TOG renderer\n\
         // (`voronoiPatterns.ts`). The committed strings are spec data: a blake3 pin\n\
         // in the crate tests fails on any edit that does not come from the mint\n\
         // binary.\n\n",
    );
    writeln!(
        source,
        "pub const VORONOI_PATTERNS: [&str; {}] = [",
        patterns.len()
    )
    .expect("writing to a String cannot fail");
    for pattern in patterns {
        // validate_path_data restricts the alphabet to characters that need no
        // Rust escaping, so a plain quoted literal is exact.
        writeln!(source, "    \"{pattern}\",").expect("writing to a String cannot fail");
    }
    source.push_str("];\n");
    source
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn extracts_each_pattern_string() {
        let source = "export const voronoiPatterns: readonly string[] = [\n\
                      'm10 10c1 1 2 2',\n\
                      'm20 20s-3-3 0 0',\n\
                      ];\n";
        let patterns = extract_patterns(source).expect("valid source");
        assert_eq!(patterns, vec!["m10 10c1 1 2 2", "m20 20s-3-3 0 0"]);
    }

    #[test]
    fn rejects_sources_without_the_array() {
        assert!(extract_patterns("export const other = [];").is_err());
        assert!(extract_patterns("export const voronoiPatterns = 'unterminated;").is_err());
    }

    #[test]
    fn rejects_non_path_characters() {
        assert!(extract_patterns("export const voronoiPatterns = ['ab\"cd'];").is_err());
    }
}
