//! Mints the committed base-palette table from the historical configuration that originally defined the palette.
//!
//! The generated Rust bytes, not the local source checkout, are the runtime
//! specification. This program exists only to make that committed data
//! reproducible when the palette table is intentionally updated.

use std::{env, fmt::Write as _, fs, path::PathBuf};

const PALETTE_SLOTS: usize = 2_048;
const COLORS_PER_SLOT: usize = 6;
const HEX_DIGITS_PER_COLOR: usize = 6;
const HEX_DIGITS_PER_SLOT: usize = COLORS_PER_SLOT * HEX_DIGITS_PER_COLOR;

fn main() {
    let Some(source) = env::args_os().nth(1).map(PathBuf::from) else {
        usage()
    };
    let output = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/generated/palette.rs");
    let config = fs::read_to_string(&source)
        .unwrap_or_else(|error| panic!("read {}: {error}", source.display()));
    let colors =
        extract_colors(&config).unwrap_or_else(|error| panic!("{}: {error}", source.display()));
    let palette =
        parse_palette(colors).unwrap_or_else(|error| panic!("{}: {error}", source.display()));

    fs::create_dir_all(output.parent().expect("palette output has a parent"))
        .unwrap_or_else(|error| panic!("create {}: {error}", output.display()));
    fs::write(&output, mint_source(&palette))
        .unwrap_or_else(|error| panic!("write {}: {error}", output.display()));
    println!("wrote {} from {}", output.display(), source.display());
}

/// The source lives in the TOG repository, which is not part of this one, so
/// its location is always given rather than assumed.
fn usage() -> ! {
    eprintln!(
        "usage: mint_palette <path to TOG's packages/contracts/svgConfig.json>\n\
         Reads the palette from that file's \"colors\" string and rewrites \
         src/generated/palette.rs."
    );
    std::process::exit(2);
}

fn extract_colors(config: &str) -> Result<&str, &'static str> {
    let key = config.find("\"colors\"").ok_or("missing colors key")?;
    let after_key = &config[key + "\"colors\"".len()..];
    let value_start = after_key.find('"').ok_or("colors value is not a string")? + 1;
    let value = &after_key[value_start..];
    let value_end = value.find('"').ok_or("unterminated colors string")?;
    Ok(&value[..value_end])
}

fn parse_palette(colors: &str) -> Result<[[[u8; 3]; COLORS_PER_SLOT]; PALETTE_SLOTS], String> {
    let hex = colors
        .strip_prefix("0x")
        .ok_or_else(|| "colors string must begin with 0x".to_owned())?;
    let expected_length = PALETTE_SLOTS * HEX_DIGITS_PER_SLOT;
    if hex.len() != expected_length {
        return Err(format!(
            "colors string has {} hex digits; expected {expected_length}",
            hex.len()
        ));
    }

    let mut palette = [[[0; 3]; COLORS_PER_SLOT]; PALETTE_SLOTS];
    for (slot, colors) in palette.iter_mut().enumerate() {
        for (color_index, color) in colors.iter_mut().enumerate() {
            let offset = slot * HEX_DIGITS_PER_SLOT + color_index * HEX_DIGITS_PER_COLOR;
            for (channel_index, channel) in color.iter_mut().enumerate() {
                *channel = parse_hex_byte(
                    &hex[offset + channel_index * 2..offset + channel_index * 2 + 2],
                )?;
            }
        }
    }
    Ok(palette)
}

fn parse_hex_byte(value: &str) -> Result<u8, String> {
    u8::from_str_radix(value, 16).map_err(|error| format!("invalid color byte {value:?}: {error}"))
}

fn mint_source(palette: &[[[u8; 3]; COLORS_PER_SLOT]; PALETTE_SLOTS]) -> String {
    let mut source = String::from(
        "// @generated by src/bin/mint_palette.rs — do not edit\n\n\
         // This committed data is the base palette contract shared by every port.\n\n\
         #[allow(clippy::large_const_arrays)]\n\
         pub const PALETTE_BASE: [[[u8; 3]; 6]; 2048] = [\n",
    );
    for colors in palette {
        source.push_str("    [");
        for color in colors {
            write!(source, "[{}, {}, {}],", color[0], color[1], color[2])
                .expect("writing to a String cannot fail");
        }
        source.push_str("],\n");
    }
    source.push_str("];\n");
    source
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_each_slot_and_color() {
        let colors = format!("0x{}", "010203".repeat(PALETTE_SLOTS * COLORS_PER_SLOT));
        let palette = parse_palette(&colors).expect("valid palette");
        assert_eq!(palette[0][0], [1, 2, 3]);
        assert_eq!(palette[PALETTE_SLOTS - 1][COLORS_PER_SLOT - 1], [1, 2, 3]);
    }

    #[test]
    fn rejects_a_wrong_length() {
        assert!(parse_palette("0x010203").is_err());
    }
}
