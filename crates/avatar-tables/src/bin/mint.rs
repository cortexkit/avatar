//! Regenerates the committed numeric tables used as deterministic spec data.
//!
//! `f64` carries 53 bits of significand precision, comfortably exceeding the
//! 30 and 32 fractional bits stored here. It is used only to mint these files:
//! the committed bytes, not the minting environment or its math library, are
//! the runtime specification consumed by every port.

use std::{
    fmt::{Display, Write as _},
    fs,
    path::PathBuf,
};

const SIN_SAMPLES: usize = 4096;
const EASING_SAMPLES: usize = 256;
const Q30_ONE: u64 = 1 << 30;
const Q32_ONE: u64 = 1 << 32;

fn main() {
    let output = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/generated/tables.rs");
    fs::write(&output, mint_source()).expect("write generated table source");
    println!("wrote {}", output.display());
}

// Offline table minting pins the platform formula's results as committed data;
// runtime geometry reads those integers rather than calling these methods.
#[allow(clippy::disallowed_methods)]
fn mint_source() -> String {
    let sine: [u32; SIN_SAMPLES] = std::array::from_fn(|index| {
        round_nonnegative(
            ((index as f64 / SIN_SAMPLES as f64) * std::f64::consts::FRAC_PI_2).sin()
                * Q30_ONE as f64,
        ) as u32
    });
    let linear = easing_table(|t| t);
    let expo = easing_table(|t| {
        if t == 0.0 {
            0.0
        } else {
            2.0_f64.powf(10.0 * t - 10.0)
        }
    });
    let in_circ = easing_table(|t| 1.0 - (1.0 - t * t).sqrt());
    let in_quint = easing_table(|t| t.powi(5));
    let in_out_circ = easing_table(|t| {
        if t < 0.5 {
            (1.0 - (1.0 - (2.0 * t).powi(2)).sqrt()) / 2.0
        } else {
            ((1.0 - (-2.0 * t + 2.0).powi(2)).sqrt() + 1.0) / 2.0
        }
    });

    let mut source = String::from(
        "// @generated by src/bin/mint.rs — do not edit\n\n\
         // This committed data replaces platform math at runtime so every port\n\
         // evaluates the same enumerable numeric contract.\n\n",
    );
    write_table(&mut source, "SIN_QUARTER", "u32", &sine);
    write_table(&mut source, "EASE_LINEAR", "u64", &linear);
    write_table(&mut source, "EASE_EXPO", "u64", &expo);
    write_table(&mut source, "EASE_IN_CIRC", "u64", &in_circ);
    write_table(&mut source, "EASE_IN_QUINT", "u64", &in_quint);
    write_table(&mut source, "EASE_IN_OUT_CIRC", "u64", &in_out_circ);
    source
}

fn easing_table(easing: impl Fn(f64) -> f64) -> [u64; EASING_SAMPLES] {
    std::array::from_fn(|index| {
        let value = easing(index as f64 / (EASING_SAMPLES - 1) as f64);
        round_nonnegative(value * Q32_ONE as f64).min(Q32_ONE)
    })
}

fn round_nonnegative(value: f64) -> u64 {
    (value + 0.5).floor() as u64
}

fn write_table<T: Display>(source: &mut String, name: &str, type_name: &str, values: &[T]) {
    if !source.ends_with("\n\n") {
        source.push('\n');
    }

    writeln!(
        source,
        "pub const {name}: [{type_name}; {}] = [",
        values.len()
    )
    .unwrap();
    for chunk in values.chunks(8) {
        write!(source, "    ").unwrap();
        for (position, value) in chunk.iter().enumerate() {
            if position > 0 {
                write!(source, " ").unwrap();
            }
            write!(source, "{value},").unwrap();
        }
        writeln!(source).unwrap();
    }
    writeln!(source, "];").unwrap();
}
